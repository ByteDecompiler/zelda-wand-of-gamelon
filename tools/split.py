"""Split cdi_zelda.mod into pieces the build puts back together.

Usage: python -I tools/split.py [--version fr|de|nl] [module]
The default module is extract/modules/cdi_zelda.mod (English), or extract/DE/modules/cdi_zelda.mod with
--version de (and so on); another version's files go to asm/de/, bin/de/ and config/de/ instead.

Writes (all contain the game's own bytes: never publish them):
  bin/header.bin       module header and name ($0000-$0052)
  bin/tail.bin         constant data, initialized data and init refs after the last function, without the CRC
  asm/<name>.s         one file per named function (and per unnamed code gap): exact dc.w words, with the
                       disassembly as comments
and config/functions.txt, the list of code pieces in module order: start, end, name.
A named function runs from its 'link a6' to the end of its MacsBug name; code between the previous
function's end and the next 'link' is an unnamed gap (assembly routines), named gap_<start>. A 'link a6'
right after an 'rts' inside a named range starts a C function without a MacsBug name, named fn_<start>.
"""
import os
import re
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools", "scripts"))
from gamefuncs import disasm, functions  # noqa: E402

CODE_START = 0x52
# The routines without a MacsBug name are the NVRAM file library, the same code as in Link: The Faces of
# Evil. Their addresses move between versions, so they are named by their offset from the first one.
# Two of them are hand-written assembly (they use a2, bra.w everywhere and bit tests on data bytes, which
# MPW C doesn't emit): the NVRAM name encoder and decoder.
UNNAMED = {0x000: "nvr_free_mem", 0x02A: "nvr_alloc_mem", 0x056: "nvr_write", 0x0C2: "nvr_read",
           0x128: "nvr_open_into", 0x230: "nvr_open", 0x288: "nvr_delete", 0x2BA: "nvr_create",
           0x41E: "nvr_close", 0x49A: "nvr_close_free", 0x4C2: "nvr_check_name", 0x504: "nvr_checksum",
           0x554: "nvr_read_host", 0x5EA: "nvr_pack_name", 0x74A: "nvr_unpack_name"}
ASSEMBLY = {0x5EA, 0x74A}


def starts_c_function(i):
    """A C function starts with 'link a6' or, when MPW C leaves out the frame (some functions built with
    -mbg off), by saving registers: 'movem.l ...,-(a7)' or 'move.l <reg>,-(a7)'."""
    if i.mnemonic == "link.w":
        return i.op_str.startswith("a6")
    return (i.mnemonic in ("movem.l", "move.l") and i.op_str.endswith("-(a7)")
            and re.match(r"([ad][0-7][-/,]?)+ ?,? ?-\(a7\)$", i.op_str.replace(" ", "")) is not None)


def pieces(data):
    """Code pieces in module order: (start, code end, end, name, kind).
    kind: func = named function, fn = C function without a MacsBug name (a 'link a6' right after an
    'rts' inside a named range; named fn_<start>), asm = such a routine that is hand-written assembly,
    gap = unnamed assembly."""
    out, prev = [], CODE_START
    for name, (_, code_end, end) in functions(data).items():
        start = prev
        while start < code_end and data[start:start + 2] != b"\x4e\x56":
            start += 2
        if start != prev:
            out.append((prev, start, start, f"gap_{prev:05X}", "gap"))
        ins = disasm(data[start:code_end], start)
        cuts = [ins[j + 1].address for j in range(len(ins) - 1)
                if ins[j].mnemonic == "rts" and starts_c_function(ins[j + 1])]
        for a, b in zip([start] + cuts, cuts):
            out.append((a, b, b, f"fn_{a:05X}", "fn"))
        out.append((cuts[-1] if cuts else start, code_end, end, name, "func"))
        prev = end
    base = next((p[0] for p in out if p[4] == "fn"), 0)
    out = [(a, b, c, UNNAMED.get(a - base, name), "asm" if a - base in ASSEMBLY else kind) if kind == "fn"
           else (a, b, c, name, kind) for a, b, c, name, kind in out]
    return out, prev


def write_asm(path, data, start, code_end, end, name, kind):
    note = {"gap": " (unnamed assembly)", "fn": " (C function without a MacsBug name)",
            "asm": " (hand-written assembly, called like a C function)"}.get(kind, "")
    lines = [f"; {name}: ${start:05X}-${end:05X}{note}",
             "; Generated by tools/split.py from the game's own bytes. Never publish."]
    for i in disasm(data[start:code_end], start):
        words = ",".join(f"${i.bytes[k] << 8 | i.bytes[k + 1]:04X}" for k in range(0, len(i.bytes), 2))
        lines.append(f"    dc.w {words:<32} ; {i.address:05X}  {i.mnemonic} {i.op_str}".rstrip())
    done = start + sum(len(i.bytes) for i in disasm(data[start:code_end], start))
    for a in range(done, end, 2):                     # MacsBug name, or bytes the disassembler stopped at
        w = struct.unpack_from(">H", data, a)[0]
        text = "".join(chr(b) if 32 <= b < 127 else "." for b in data[a:a + 2])
        lines.append(f"    dc.w ${w:04X}{'':<27} ; {a:05X}  {'MacsBug name' if a >= code_end else 'data'} '{text}'")
    open(path, "w", newline="\n").write("\n".join(lines) + "\n")


def write_jump_table(data, config):
    """config/jumptable.txt: the MPW jump table, from the module's initialized data. The data starts with
    two longs (offset, size), then the A5 world's first 8 bytes, then 8-byte entries: segment number,
    'jmp abs.l', address in the module. MPW's jump table starts at A5+32 and the code calls 'jsr N(a5)' with
    N = the entry's jmp, so the entry at data offset 8 + 8k is called as jsr (8 + 8k + $1a)(a5)."""
    idata, = struct.unpack_from(">I", data, 0x40)
    size, = struct.unpack_from(">I", data, idata + 4)
    rows = ["# MPW jump table (generated by tools/split.py): A5 offset of the jmp, segment, address.",
            "# A call from another segment goes through it: jsr <a5 offset>(a5)."]
    for off in range(8, size, 8):
        seg, op, addr = struct.unpack_from(">HHI", data, idata + 8 + off)
        assert op == 0x4EF9, f"jump table entry at data offset {off:#x} isn't a jmp"
        rows.append(f"{off + 0x1a:#06x}  {seg}  {addr:06X}")
    open(os.path.join(config, "jumptable.txt"), "w", newline="\n").write("\n".join(rows) + "\n")


def main():
    args = sys.argv[1:]
    version = "en"
    if args[:1] == ["--version"]:
        version, args = args[1], args[2:]
    sub = [] if version == "en" else [version]
    src = args[0] if args else os.path.join(ROOT, "extract", *[v.upper() for v in sub], "modules", "cdi_zelda.mod")
    data = open(src, "rb").read()
    size, = struct.unpack_from(">I", data, 4)
    assert size == len(data), "module size in the header doesn't match the file"
    asm, bin_, config = (os.path.join(ROOT, d, *sub) for d in ("asm", "bin", "config"))
    for d in (asm, bin_, config):
        os.makedirs(d, exist_ok=True)
    ps, tail_start = pieces(data)
    open(os.path.join(bin_, "header.bin"), "wb").write(data[:CODE_START])
    open(os.path.join(bin_, "tail.bin"), "wb").write(data[tail_start:size - 3])
    rows = ["# Code pieces of cdi_zelda.mod in module order (generated by tools/split.py).",
            "# start   end     kind  name"]
    for start, code_end, end, name, kind in ps:
        write_asm(os.path.join(asm, f"{name}.s"), data, start, code_end, end, name, kind)
        rows.append(f"{start:06X}  {end:06X}  {kind:<4}  {name}")
    open(os.path.join(config, "functions.txt"), "w", newline="\n").write("\n".join(rows) + "\n")
    write_jump_table(data, config)
    print(f"{len(ps)} code pieces ({sum(1 for p in ps if p[4] == 'func')} named functions, "
          f"{sum(1 for p in ps if p[4] == 'fn')} unnamed C functions), "
          f"code ${CODE_START:X}-${tail_start:X}, tail ${tail_start:X}-${size - 3:X}")


if __name__ == "__main__":
    main()
