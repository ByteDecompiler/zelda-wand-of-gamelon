"""Find the PC-relative references between code pieces, for a build where code can change size.

Usage (WSL, needs Capstone): ~/foe_tools/venv/bin/python -I tools/relocs.py [extract/modules/cdi_zelda.mod]
Writes config/relocs.txt.

The C functions are relinked from their objects, which carry their own relocations. Everything else is
copied as the game's bytes: the assembly pieces (gap_*, nvr_pack_name/nvr_unpack_name) and the module's tail
(segment 8: the A5 data unpacker; segment 9: the
OS-9/CD-i library). When code before or between them moves, their PC-relative references that point
into another piece (a call, a branch, a 'lea d16(pc)') must be adjusted. This scans those pieces
instruction by instruction and lists each such reference:
  <address of the instruction> <kind> <target address>
kind: w = 16-bit displacement in the word after the opcode (Bcc.w/BSR.w/BRA.w, and any instruction whose
first operand is d16(pc): jsr, jmp, lea, pea, move ...); b = 8-bit displacement in the opcode (Bcc.b).
"""
import os
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools", "scripts"))
from gamefuncs import disasm  # noqa: E402

# Code ranges of the tail that hold instructions (the rest is data): the A5 data unpacker (found by its
# first bytes) and the library (from the lowest segment 9 address in the jump table). Both are the same
# code as in Link: The Faces of Evil, so their lengths are fixed.
UNPACKER, UNPACKER_LEN, LIBRARY_LEN = bytes.fromhex("48e7fff0424741fa"), 0xF8, 0x1FD6


def tail_code(data):
    unpacker = data.find(UNPACKER)
    library = min(int(line.split()[2], 16) for line in open(os.path.join(ROOT, "config", "jumptable.txt"))
                  if not line.startswith("#") and line.split()[1] == "9")
    return [(unpacker, unpacker + UNPACKER_LEN), (library, library + LIBRARY_LEN)]


def blocks():
    """(start, end, name) of every piece, then the tail."""
    out = []
    for line in open(os.path.join(ROOT, "config", "functions.txt")):
        if line.strip() and not line.startswith("#"):
            start, end, kind, name = line.split()
            out.append((int(start, 16), int(end, 16), name, kind))
    return out


def scan(data, start, end):
    """Yield (address, kind, target) for each PC-relative operand in data[start:end]."""
    pos = start
    while pos < end:
        ins = disasm(data[pos:end], pos)
        if not ins:
            pos += 2                                    # skip a word the disassembler can't decode
            continue
        for i in ins:
            a = i.address
            op = struct.unpack_from(">H", data, a)[0]
            if op & 0xF000 == 0x6000:                   # Bcc / BRA / BSR
                d8 = op & 0xFF
                if d8 == 0:
                    yield a, "w", a + 2 + struct.unpack_from(">h", data, a + 2)[0]
                elif d8 != 0xFF:
                    yield a, "b", a + 2 + (d8 - 256 if d8 & 0x80 else d8)
            elif op & 0x3F == 0x3A and i.size >= 4 and "(pc)" in i.op_str and "#" not in i.op_str:
                yield a, "w", a + 2 + struct.unpack_from(">h", data, a + 2)[0]
            pos = a + i.size


def main():
    mod = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "extract", "modules", "cdi_zelda.mod")
    data = open(mod, "rb").read()
    ps = blocks()
    tail_start = ps[-1][1]
    code = tail_code(data)
    starts = sorted([(s, e, n) for s, e, n, _ in ps] + [(tail_start, code[1][1], "tail")])

    def block_of(addr):
        for s, e, n in starts:
            if s <= addr < e:
                return n
        return None

    rows = ["# PC-relative references from copied code into another piece (generated by tools/relocs.py).",
            "# address of the instruction, kind (w: 16-bit, b: 8-bit displacement), target address"]
    ranges = [(s, e, n) for s, e, n, k in ps if k in ("gap", "asm")] + \
             [(s, e, "tail") for s, e in code]
    count = 0
    for s, e, n in ranges:
        for a, kind, target in scan(data, s, e):
            tb = block_of(target)
            if tb is None or tb == n:
                continue
            rows.append(f"{a:06X}  {kind}  {target:06X}   # {n} -> {tb}")
            count += 1
    open(os.path.join(ROOT, "config", "relocs.txt"), "w", newline="\n").write("\n".join(rows) + "\n")
    print(f"{count} references between pieces")


if __name__ == "__main__":
    main()
